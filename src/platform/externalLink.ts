/** A user-selected public community link opens alongside the game and cannot access its window. */
export function openExternalLink(url: string): void {
  const link = document.createElement("a");
  link.href = url;
  link.target = "_blank";
  link.rel = "noopener noreferrer";
  document.body.append(link);
  link.click();
  link.remove();
}
